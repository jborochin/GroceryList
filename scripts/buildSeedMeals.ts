/**
 * src/data/mealCatalog.json → supabase/seed_meals.sql generator.
 *
 * The bundled mealCatalog.json is the offline source of truth for the shared
 * meal catalog; public.meals is its updatable server mirror (see
 * supabase/schema.sql and src/lib/mealCatalogSync.ts). This script regenerates
 * the idempotent seed SQL from the JSON so the two stay in sync — crucially it
 * emits EVERY column, including image_url and instructions, which the older
 * hand-rolled seed_meals.sql omitted.
 *
 * Output is parameterless SQL literals for the Supabase SQL editor (service
 * role); re-running is safe (upsert on id).
 *
 * Usage:
 *   npm run seed:build
 *   npx tsx scripts/buildSeedMeals.ts --out supabase/seed_meals.sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Meal } from '../src/types';

const CATALOG_PATH = 'src/data/mealCatalog.json';
const DEFAULT_OUT = 'supabase/seed_meals.sql';

// --- SQL literal helpers (same style as scripts/importMealDb.ts) -----------
const sqlStr = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sqlTextArray = (arr: string[]) =>
  arr.length === 0 ? `ARRAY[]::text[]` : `ARRAY[${arr.map(sqlStr).join(', ')}]::text[]`;
const sqlJsonb = (v: unknown) => `${sqlStr(JSON.stringify(v))}::jsonb`;
const sqlNum = (n: number) => String(n);
const sqlNullableNum = (n: number | null | undefined) =>
  n == null ? 'NULL' : String(n);
const sqlNullableStr = (s: string | null | undefined) =>
  s == null || s === '' ? 'NULL' : sqlStr(s);
const sqlNullableTextArray = (arr: string[] | null | undefined) =>
  arr == null || arr.length === 0 ? 'NULL' : sqlTextArray(arr);

function rowToValues(m: Meal): string {
  return `  (${[
    sqlStr(m.id),
    sqlStr(m.title),
    sqlStr(m.cuisine),
    sqlTextArray(m.slots),
    sqlTextArray(m.dietaryTags),
    sqlNum(m.servings),
    sqlJsonb(m.ingredients),
    sqlJsonb(m.nutritionPerServing),
    sqlNullableNum(m.prepTimeMinutes),
    sqlNullableStr(m.imageUrl),
    sqlNullableTextArray(m.instructions),
  ].join(', ')})`;
}

function buildSql(meals: Meal[]): string {
  const header = [
    '-- Generated by scripts/buildSeedMeals.ts from src/data/mealCatalog.json.',
    '-- Re-run safely (upsert on id). Apply after schema.sql creates public.meals.',
    '-- Do not edit by hand — edit mealCatalog.json and re-run `npm run seed:build`.',
    '',
  ].join('\n');

  const columns =
    '(id, title, cuisine, slots, dietary_tags, servings, ingredients, ' +
    'nutrition_per_serving, prep_time_minutes, image_url, instructions)';

  const onConflict = [
    'on conflict (id) do update set',
    '  title = excluded.title,',
    '  cuisine = excluded.cuisine,',
    '  slots = excluded.slots,',
    '  dietary_tags = excluded.dietary_tags,',
    '  servings = excluded.servings,',
    '  ingredients = excluded.ingredients,',
    '  nutrition_per_serving = excluded.nutrition_per_serving,',
    '  prep_time_minutes = excluded.prep_time_minutes,',
    '  image_url = excluded.image_url,',
    '  instructions = excluded.instructions,',
    '  updated_at = now();',
  ].join('\n');

  return `${header}insert into public.meals\n  ${columns}\nvalues\n${meals
    .map(rowToValues)
    .join(',\n')}\n${onConflict}\n`;
}

function parseOut(argv: string[]): string {
  const i = argv.indexOf('--out');
  return i >= 0 && argv[i + 1] ? argv[i + 1] : DEFAULT_OUT;
}

function main(): void {
  const out = parseOut(process.argv.slice(2));
  const meals = JSON.parse(readFileSync(resolve(process.cwd(), CATALOG_PATH), 'utf8')) as Meal[];
  if (!Array.isArray(meals) || meals.length === 0) {
    console.error(`No meals found in ${CATALOG_PATH}.`);
    process.exit(1);
  }
  const outPath = resolve(process.cwd(), out);
  writeFileSync(outPath, buildSql(meals), 'utf8');
  console.log(`Wrote ${meals.length} meals → ${out}`);
}

main();
