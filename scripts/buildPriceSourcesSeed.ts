/**
 * src/data/priceDatabase.json → supabase/seed_price_sources.sql generator.
 *
 * public.price_sources is the enrollment table for live pricing: one row per
 * bundled price key, holding the search term, the (eventually) pinned retail
 * SKU, and the baseline price the sanity band compares candidates against.
 *
 * This is how a NEW ingredient gets live pricing with no mapping work: add the
 * priceDatabase.json row (already mandatory — mealCatalogPriceCoverage.test.ts
 * enforces it), re-run this script, apply the SQL. The next weekly refresh
 * searches for it and publishes if the match clears the confidence gate. Until
 * then it prices off the bundled hand-estimate, i.e. today's behavior.
 *
 * The generated upsert refreshes ONLY baseline_price_per_unit/baseline_unit and
 * search_term. It never touches reviewed, kroger_product_id, confidence, or
 * notes — so human review work is permanent and re-running is always safe.
 *
 * Usage:
 *   npm run prices:seed-sources
 *   npx tsx scripts/buildPriceSourcesSeed.ts --out supabase/seed_price_sources.sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import purchaseProfiles from '../src/data/purchaseProfiles.json';
import { normalizeName } from '../src/utils/normalizeName';

const PRICE_DB_PATH = 'src/data/priceDatabase.json';
const DEFAULT_OUT = 'supabase/seed_price_sources.sql';

interface PriceEntry {
  pricePerUnit: number;
  unit: string;
}

interface PurchaseProfile {
  sellUnit: string;
  packSize: number;
  grams?: Record<string, number>;
}

const sqlStr = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * Explicit purchase profiles by normalized name.
 *
 * Mirrored onto the row so the on-demand edge function can price a cross-family SKU
 * without importing the app's purchaseProfile module (which reaches fuse.js). Only
 * EXPLICIT entries travel: the derived default is `{ sellUnit: price unit, packSize: 1 }`,
 * which the function reconstructs from baseline_unit, so sending it would be noise.
 */
const PROFILES: Record<string, PurchaseProfile> = (() => {
  const out: Record<string, PurchaseProfile> = {};
  for (const [key, value] of Object.entries(purchaseProfiles as Record<string, unknown>)) {
    // `_`-prefixed keys are documentation notes, not profiles.
    if (key.startsWith('_') || typeof value !== 'object' || value === null) continue;
    out[normalizeName(key)] = value as PurchaseProfile;
  }
  return out;
})();

interface SourceRow {
  normalized: string;
  searchTerm: string;
  price: number;
  unit: string;
  profile: PurchaseProfile | null;
}

/**
 * Build one row per price key. The primary key is the normalized name (the
 * universal join key), but the search term is the RAW key — "eggs" searches a
 * retail catalog better than its singularized "egg".
 *
 * Two raw keys that normalize to the same string would collide on the primary
 * key and silently drop one of them, so that fails loudly here instead.
 */
export function buildRows(db: Record<string, PriceEntry>): SourceRow[] {
  const rows: SourceRow[] = [];
  const seen = new Map<string, string>();

  for (const [key, entry] of Object.entries(db)) {
    const normalized = normalizeName(key);
    if (!normalized) throw new Error(`priceDatabase.json key "${key}" normalizes to an empty string`);

    const previous = seen.get(normalized);
    if (previous !== undefined) {
      throw new Error(
        `priceDatabase.json keys "${previous}" and "${key}" both normalize to "${normalized}" — ` +
          `they would collide on price_sources.normalized_name. Remove or rename one.`
      );
    }
    seen.set(normalized, key);

    rows.push({
      normalized,
      searchTerm: key,
      price: entry.pricePerUnit,
      unit: entry.unit,
      profile: PROFILES[normalized] ?? null,
    });
  }

  return rows;
}

function rowToValues(r: SourceRow): string {
  return `  (${[
    sqlStr(r.normalized),
    sqlStr(r.searchTerm),
    String(r.price),
    sqlStr(r.unit),
    r.profile === null ? 'null' : `${sqlStr(JSON.stringify(r.profile))}::jsonb`,
  ].join(', ')})`;
}

export function buildSql(rows: SourceRow[]): string {
  const header = [
    '-- Generated by scripts/buildPriceSourcesSeed.ts from src/data/priceDatabase.json.',
    '-- Apply after schema.sql creates public.price_sources. Re-running is safe:',
    '-- the upsert refreshes only the baseline price/unit and search term, and',
    '-- deliberately leaves reviewed, kroger_product_id, confidence and notes alone',
    '-- so human review work survives regeneration.',
    "-- Do not edit by hand — edit priceDatabase.json and re-run `npm run prices:seed-sources`.",
    '',
  ].join('\n');

  const onConflict = [
    'on conflict (normalized_name) do update set',
    '  search_term = excluded.search_term,',
    '  baseline_price_per_unit = excluded.baseline_price_per_unit,',
    '  baseline_unit = excluded.baseline_unit,',
    '  purchase_profile = excluded.purchase_profile,',
    '  updated_at = now();',
  ].join('\n');

  return (
    `${header}insert into public.price_sources\n` +
    '  (normalized_name, search_term, baseline_price_per_unit, baseline_unit, purchase_profile)\n' +
    `values\n${rows.map(rowToValues).join(',\n')}\n${onConflict}\n`
  );
}

function parseOut(argv: string[]): string {
  const i = argv.indexOf('--out');
  return i >= 0 && argv[i + 1] ? argv[i + 1] : DEFAULT_OUT;
}

function main(): void {
  const out = parseOut(process.argv.slice(2));
  const db = JSON.parse(
    readFileSync(resolve(process.cwd(), PRICE_DB_PATH), 'utf8')
  ) as Record<string, PriceEntry>;

  const rows = buildRows(db);
  if (rows.length === 0) {
    console.error(`No price entries found in ${PRICE_DB_PATH}.`);
    process.exit(1);
  }

  writeFileSync(resolve(process.cwd(), out), buildSql(rows), 'utf8');
  console.log(`Wrote ${rows.length} price sources → ${out}`);
}

// Only run when invoked directly, so the pure builders above stay importable by tests.
if (process.argv[1] && process.argv[1].includes('buildPriceSourcesSeed')) {
  main();
}
